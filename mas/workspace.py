# -*- coding: utf-8 -*-
"""v0.7.61: rewrite mas/workspace.py around the "one folder per run" rule.

Two rules, and they must not fight each other:

1. If the user named a workspace (``--workspace`` or the config), that
   directory is the run's workspace. The user pointed at it on purpose.
2. If nobody named one, the run gets its own folder under the state
   directory: ``<state_dir>/artifacts/<run_id>/``.

In both cases the deliverable is written into that same folder, as
``deliverable.md``. So a run always hands over exactly one folder
holding everything it produced - never a deliverable in one place and
its supporting files in another.
"""

from __future__ import annotations

import pathlib
import re
from typing import Any, Dict, List, Optional

#: The file name the deliverable takes inside a run's workspace.
DELIVERABLE_NAME = "deliverable.md"

#: The name of the sub-folder of the state directory that holds the
#: per-run workspaces.
WORKSPACES_DIRNAME = "artifacts"

#: A run id is used as a directory name. It is generated by the engine
#: (``R-<10 hex chars>``), but a caller may pass its own, so the name is
#: sanitised: no separators, no dots, nothing that could escape the
#: parent folder.
_UNSAFE_NAME_RE = re.compile(r"[^A-Za-z0-9._-]+")


def safe_run_name(run_id: Any) -> str:
    """Turn a run id into a name that is safe as a directory name."""
    text = "".join(
        ch if (ch.isalnum() or ch in "-_") else "_" for ch in str(run_id or "")
    )
    text = _UNSAFE_NAME_RE.sub("_", text).strip("._")
    return text or "run"


def workspaces_root(state_root: Any) -> pathlib.Path:
    """The folder that holds every run's workspace."""
    return pathlib.Path(state_root) / WORKSPACES_DIRNAME


def run_workspace(state_root: Any, run_id: Any) -> pathlib.Path:
    """The default folder of one run: ``<state_dir>/artifacts/<run_id>/``."""
    return workspaces_root(state_root) / safe_run_name(run_id)


def resolve_workspace(
    state_root: Any,
    run_id: Any,
    configured: Any = None,
) -> pathlib.Path:
    """The folder a run writes into.

    A workspace the user named wins - they pointed at it on purpose.
    Otherwise the run gets a folder of its own under the state
    directory, so the files it produces stay together and survive the
    process.
    """
    raw = str(configured or "").strip()
    if raw:
        return pathlib.Path(raw).expanduser()
    return run_workspace(state_root, run_id)


def ensure_workspace(path: Any) -> pathlib.Path:
    """Create the folder and return it."""
    target = pathlib.Path(path)
    target.mkdir(parents=True, exist_ok=True)
    return target


def collect_files(root: Any) -> List[Dict[str, Any]]:
    """List the files inside a workspace, relative to it.

    The deliverable is listed too - it is part of what the run
    produced - but the caller can tell it apart by its name.
    """
    base = pathlib.Path(root)
    if not base.exists():
        return []
    rows: List[Dict[str, Any]] = []
    for path in sorted(base.rglob("*")):
        if not path.is_file():
            continue
        try:
            size = path.stat().st_size
        except OSError:  # pragma: no cover - defensive
            continue
        rows.append(
            {
                "path": str(path.relative_to(base)).replace("\\", "/"),
                "absolute": str(path),
                "bytes": int(size),
            }
        )
    return rows


def workspace_reading(
    workspace: Any,
    files: Optional[List[Dict[str, Any]]] = None,
) -> str:
    """A one-line, human reading of a workspace."""
    path = str(workspace or "")
    if not path:
        return ""
    if files is None:
        count = 0
    else:
        count = len([row for row in files if row.get("path") != DELIVERABLE_NAME])
    if count == 0:
        return f"工作区：{path}（没有额外文件）"
    return f"工作区：{path}（{count} 个文件）"
